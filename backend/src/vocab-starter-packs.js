/**
 * Пять системных списков A1–A2 по 20 слов.
 * Библиотека создаёт их сама и дописывает недостающие слова.
 */

function pack(key, title, description, level, words) {
  return Object.freeze({
    key,
    title,
    description,
    level,
    icon: 'list',
    language: 'en',
    words: Object.freeze(words),
  })
}

function words(rows) {
  return rows.map(([word, gloss, partOfSpeech, phonetic]) => ({
    word,
    gloss,
    partOfSpeech,
    phonetic,
  }))
}

