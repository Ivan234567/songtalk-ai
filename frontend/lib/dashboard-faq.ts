import type { LearningLanguage } from '@/lib/learning-language';

export type FaqCategoryId =
  | 'start'
  | 'practice'
  | 'karaoke'
  | 'dictionary'
  | 'progress'
  | 'billing'
  | 'account';

export type FaqRelatedTab = 'agent' | 'dictionary' | 'karaoke' | 'progress' | 'balance' | 'account';

export type FaqItem = {
  id: string;
  category: FaqCategoryId;
  question: string;
  answer: string[];
  keywords?: string[];
  relatedTab?: FaqRelatedTab;
  relatedLabel?: string;
};

export type FaqCategory = {
  id: FaqCategoryId | 'all';
  label: string;
};

const CATEGORY_LABELS: Record<FaqCategoryId, string> = {
  start: 'Старт',
  practice: 'Практика',
  karaoke: 'Караоке',
  dictionary: 'Словарь',
  progress: 'Прогресс',
  billing: 'Оплата',
  account: 'Аккаунт',
};

export function getFaqCategoryLabel(id: FaqCategoryId): string {
  return CATEGORY_LABELS[id];
}

export function getFaqCategories(lang: LearningLanguage): FaqCategory[] {
  const ids: Array<FaqCategoryId | 'all'> = lang === 'zh'
    ? ['all', 'start', 'practice', 'dictionary', 'progress', 'billing', 'account']
    : ['all', 'start', 'practice', 'karaoke', 'dictionary', 'progress', 'billing', 'account'];
  return ids.map((id) => ({
    id,
    label: id === 'all' ? 'Все' : CATEGORY_LABELS[id],
  }));
}

export function normalizeFaqQuery(value: string): string {
  return value.toLowerCase().replace(/ё/g, 'е').trim();
}

export function faqItemMatches(item: FaqItem, query: string): boolean {
  const q = normalizeFaqQuery(query);
  if (!q) return true;
  const hay = normalizeFaqQuery(
    [item.question, item.answer.join(' '), ...(item.keywords || []), getFaqCategoryLabel(item.category)].join(' '),
  );
  return q.split(/\s+/).filter(Boolean).every((token) => hay.includes(token));
}

